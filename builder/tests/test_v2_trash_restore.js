#!/usr/bin/env node
'use strict';
/*
 * test_v2_trash_restore.js -- the delete confirmation's promise is kept.
 *
 * Run:  node builder/tests/test_v2_trash_restore.js
 *       node builder/tests/test_v2_trash_restore.js --headed
 *
 * THE DEFECT
 *   Deleting a report showed a confirmation that said, in so many words:
 *   "This moves {name} to the trash. You can restore it from History." Then:
 *     * the shelf's Trash rail entry opened a stub dialog reading
 *       "This screen is not available yet";
 *     * the History drawer's Trash chip rendered a hard-coded empty state --
 *       "Nothing here yet" -- whatever was actually in the trash;
 *     * and History is per-report, opened from inside a report the user can no
 *       longer open.
 *   The folder was on disk the whole time. Deleting was a one-way door
 *   carrying a written promise that it was not.
 *
 * WHAT IT ASSERTS, in a real browser, driving a real mouse
 *   1. the delete confirmation points at the place the restore actually lives,
 *      and does not point at History               (fails before the fix)
 *   2. deleting a report from the shelf, then opening Trash, LISTS it -- by
 *      name, with the path it came from            (fails before the fix)
 *   3. restoring it puts it back at its ORIGINAL path with its content intact,
 *      and it is on the shelf again with no manual refresh
 *                                                  (fails before the fix)
 *   4. restoring onto an occupied path is REFUSED, in words, and overwrites
 *      nothing                                     (fails before the fix)
 *   5. there is ONE place: History no longer offers a Trash filter it cannot
 *      fill                                        (fails before the fix)
 *
 * IT NEVER TOUCHES REAL REPORTS. The fixture is generated from scratch into the
 * OS temporary directory and the server is booted against THAT with --root.
 *
 * SKIPPING IS A FEATURE: no playwright-core (the public repository carries no
 * node_modules) or no system browser still runs the static half and exits 0.
 */

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const net = require('node:net');
const http = require('node:http');
const { spawn } = require('node:child_process');

const HERE = __dirname;
const REPO = path.resolve(HERE, '..', '..');
const SERVER_PY = path.join(REPO, 'builder', 'web', 'server.py');
const VIEWS = path.join(REPO, 'builder', 'web', 'assets', 'v2', 'js', 'views');
const HOME_JS = path.join(VIEWS, 'home.js');
const SYNC_JS = path.join(VIEWS, 'sync.js');

const ARGS = process.argv.slice(2);
const HEADED = ARGS.includes('--headed');
const KEEP_ROOT = ARGS.includes('--keep-root');
const VIEWPORT = { width: 1440, height: 900 };

const TRASH = 'Trash';
const DELETE = 'Delete';
const MOVE_TO_TRASH = 'Move to trash';
const RESTORE = 'Restore';
const CLOSE = 'Close';

let chromium = null;
let chromiumMissing = '';
try {
  chromium = require('playwright-core').chromium;
} catch (err) {
  chromiumMissing = 'playwright-core is not installed.  npm install, then re-run.';
}

