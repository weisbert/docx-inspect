const PROJECT_ID = '1108';
const MODULE_ID = 'CLKDIV_5G';
const DOOMED_DIR = PROJECT_ID + '/' + MODULE_ID + '/CDR';
const KEEPER_DIR = PROJECT_ID + '/' + MODULE_ID + '/PDR';
const DOOMED_TITLE = 'CLKDIV_5G CDR draft';
const KEEPER_TITLE = 'CLKDIV_5G PDR draft';
const MARKER = 'The one sentence that proves the content came back.';

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(value, null, 2), 'utf8');
}

function sampleReport(title, sentence) {
  return {
    template: 'sample',
    meta: { title: title, doc_no: 'DOC-1', version: 'V1.0' },
    outline: [{
      id: 'n-1',
      title: 'Overview',
      blocks: [{ type: 'para', runs: [{ t: sentence }], cardStart: true }],
      children: [],
    }],
  };
}

function buildReportsRoot(root) {
  fs.mkdirSync(root, { recursive: true });
  writeJson(path.join(root, 'templates', 'sample', 'config.json'),
    { id: 'sample', name: 'Sample template', styles: {} });
  writeJson(path.join(root, PROJECT_ID, 'project_meta.json'),
    { name: PROJECT_ID, description: 'Generated by this test' });
  writeJson(path.join(root, PROJECT_ID, MODULE_ID, 'project_meta.json'),
    { name: MODULE_ID, description: 'Divider block' });
  writeJson(path.join(root, ...DOOMED_DIR.split('/'), 'project.json'),
    sampleReport(DOOMED_TITLE, MARKER));
  writeJson(path.join(root, ...KEEPER_DIR.split('/'), 'project.json'),
    sampleReport(KEEPER_TITLE, 'Another report, never deleted.'));
  return root;
}

